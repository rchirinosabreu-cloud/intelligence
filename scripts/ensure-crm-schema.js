import pg from 'pg';
import { pathToFileURL } from 'node:url';

// Additive rollout only: the CRM tables are created once and never dropped, truncated or rewritten here.
// Stage/origin/priority values are TEXT with CHECK constraints so the catalog in src/lib/crmRules.js
// stays the single source of truth without PostgreSQL enum migrations.
export async function ensureCrmSchema(client) {
  await client.query('BEGIN');
  try {
    await client.query("SET LOCAL lock_timeout = '10s'; SET LOCAL statement_timeout = '60s'");
    await client.query('SELECT pg_advisory_xact_lock(20260918, 1)');
    await client.query(`CREATE TABLE IF NOT EXISTS "CrmLead" (
      id TEXT PRIMARY KEY,
      consecutive INTEGER GENERATED BY DEFAULT AS IDENTITY,
      "legacyCode" TEXT UNIQUE,
      origin TEXT NOT NULL DEFAULT 'OTRO',
      "originDetail" TEXT,
      "enteredAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
      "enteredAtEstimated" BOOLEAN NOT NULL DEFAULT false,
      "contactName" TEXT,
      company TEXT,
      "companyKey" TEXT,
      "jobTitle" TEXT,
      phone TEXT,
      email TEXT,
      "linkedinUrl" TEXT,
      "serviceInterest" TEXT,
      language TEXT,
      "allowedContact" TEXT,
      priority TEXT NOT NULL DEFAULT 'MEDIA' CHECK (priority IN ('ALTA','MEDIA','BAJA')),
      "publishedAt" DATE,
      "callDeadlineAt" DATE,
      "firstContactAt" TIMESTAMPTZ,
      "proposalSentAt" TIMESTAMPTZ,
      "lastActivityAt" TIMESTAMPTZ,
      "closedAt" TIMESTAMPTZ,
      stage TEXT NOT NULL DEFAULT 'POR_GESTIONAR' CHECK (stage IN ('POR_GESTIONAR','CONTACTADO','CITA_SOLICITADA','CITA_REALIZADA','PROPUESTA_ENVIADA','NEGOCIACION','ESPERANDO_CLIENTE','SIN_RESPUESTA','APROBADA','GANADO','PERDIDO','DESCARTADO')),
      "trafficLightOverride" TEXT CHECK ("trafficLightOverride" IS NULL OR "trafficLightOverride" IN ('VERDE','AMARILLO','ROJO')),
      "trafficLightReason" TEXT,
      "nextAction" TEXT,
      "nextFollowUpAt" DATE,
      "ownerId" TEXT REFERENCES "TeamMember"(id),
      "quotedValue" NUMERIC(14,2),
      currency TEXT NOT NULL DEFAULT 'COP',
      "lostReason" TEXT,
      "clientId" TEXT REFERENCES "Client"(id),
      "quotationId" TEXT REFERENCES "Quotation"(id),
      notes TEXT,
      "createdById" TEXT REFERENCES "User"(id),
      "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
      "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
      "archivedAt" TIMESTAMPTZ
    );
    CREATE INDEX IF NOT EXISTS "CrmLead_stage_idx" ON "CrmLead"(stage, "archivedAt");
    CREATE INDEX IF NOT EXISTS "CrmLead_followup_idx" ON "CrmLead"("ownerId", "nextFollowUpAt");
    CREATE INDEX IF NOT EXISTS "CrmLead_origin_idx" ON "CrmLead"(origin);
    CREATE INDEX IF NOT EXISTS "CrmLead_company_idx" ON "CrmLead"("companyKey");
    CREATE INDEX IF NOT EXISTS "CrmLead_entered_idx" ON "CrmLead"("enteredAt");
    CREATE TABLE IF NOT EXISTS "CrmActivity" (
      id TEXT PRIMARY KEY,
      "leadId" TEXT NOT NULL REFERENCES "CrmLead"(id),
      type TEXT NOT NULL CHECK (type IN ('LLAMADA','CORREO','WHATSAPP','MENSAJE_LINKEDIN','REUNION','PROPUESTA_ENVIADA','RESPUESTA_CLIENTE','NOTA','CAMBIO_ETAPA')),
      "occurredAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
      note TEXT,
      result TEXT,
      "nextAction" TEXT,
      "nextFollowUpAt" DATE,
      "fromStage" TEXT,
      "toStage" TEXT,
      "authorId" TEXT REFERENCES "User"(id),
      "requestId" TEXT,
      "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
      "editedAt" TIMESTAMPTZ,
      UNIQUE("authorId","requestId")
    );
    CREATE INDEX IF NOT EXISTS "CrmActivity_lead_idx" ON "CrmActivity"("leadId", "occurredAt");
    CREATE INDEX IF NOT EXISTS "CrmActivity_author_idx" ON "CrmActivity"("authorId");`);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK').catch(rollbackError => console.error('[CRM schema] Rollback failed:', rollbackError.message));
    throw error;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const client = new pg.Client({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10000 });
  try {
    if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required.');
    await client.connect();
    await ensureCrmSchema(client);
    console.log('[CRM schema] Ready; existing leads and activities preserved.');
  } catch (error) {
    console.error('[CRM schema] Failed:', error.message);
    process.exitCode = 1;
  } finally {
    await client.end().catch(error => console.error('[CRM schema] Disconnect failed:', error.message));
  }
}
