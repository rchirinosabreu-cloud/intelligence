import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { ensureFinancialOffsets } from '../scripts/ensure-financial-offset-schema.js';
import { financialCorrectionDatabase } from './support/financialCorrectionDatabase.js';
import { briaTestDatabaseUrl } from './support/briaTestDatabase.js';
import { offsetOptions, readOffset, createOffset, reverseOffset } from '../src/services/financialOffsetService.js';
import { listPayablesLedger, reversePayablePayment, payPayable } from '../src/services/accountsPayableService.js';
import { reverseReceivablePayment, updateReceivablePayment } from '../src/services/receivablePaymentService.js';
import { deleteReceivable } from '../src/services/financialReceivableService.js';

test('cruce nativo y reversión en PostgreSQL aislado', { skip: !briaTestDatabaseUrl(), timeout: 90000 }, async t => {
  const fixture = await financialCorrectionDatabase({ additionalTables: ['Client', 'AccountsReceivable', 'ReceivablePayment', 'ReceivableItem', 'ReceivablePaymentDocument', 'AccountsPayableDocument'] });
  t.after(fixture.close);
  const { db, actor } = fixture;
  const connection = new pg.Client({ connectionString: briaTestDatabaseUrl() });
  await connection.connect(); t.after(() => connection.end());
  await connection.query(`SET search_path TO "${new URL(fixture.databaseUrl).searchParams.get('schema')}"`);
  await ensureFinancialOffsets(connection); await ensureFinancialOffsets(connection);
  const seed = async () => {
    const client = await db.client.create({ data: { name: 'Cliente ficticio', slug: randomUUID() } });
    const party = await db.thirdParty.create({ data: { name: 'Cliente ficticio', kind: 'PROVEEDOR', clientId: client.id } });
    const ar = await db.accountsReceivable.create({ data: { clientId: client.id, amount: 960000, concept: 'Servicio de agencia', period: new Date('2026-09-01'), year: 2026, month: 9 } });
    const ap = await db.accountsPayable.create({ data: { thirdPartyId: party.id, amount: 1000000, concept: 'Servicio recibido', category: 'OPERATIVO', receivedAt: new Date('2026-09-01'), year: 2026, month: 9 } });
    const prepare = async (amount = 960000) => ({ payableId: ap.id, amount, settledAt: '2026-09-18', authorizedBy: 'Dirección · muestra', reason: 'Cruce acordado de ambas obligaciones', requestId: randomUUID(), expectedRevision: (await offsetOptions(db, ar.id, actor)).options.find(row => row.id === ap.id).revision });
    return { ar, ap, party, prepare };
  };
  await t.test('960.000 reduce ambos saldos, sin dinero; reintento y reversión conservan filas y soportes', async () => {
    const { ar, ap, prepare } = await seed(); const input = await prepare();
    const result = await createOffset(db, ar.id, input, actor);
    assert.equal(result.receivable.outstanding, 0); assert.equal(result.payable.outstanding, 40000);
    assert.equal(result.receivable.status, 'SALDADO'); assert.equal(result.payable.status, 'PARCIAL');
    assert.equal(await db.financialRecord.count(), 0);
    assert.equal((await createOffset(db, ar.id, input, actor)).replayed, true);
    assert.equal(await db.payablePayment.count({ where: { payableId: ap.id } }), 1);
    const ledger = await listPayablesLedger(db, { year: 2026, month: 9 });
    assert.equal(ledger.totals.paidInPeriod, 0); assert.equal(ledger.totals.compensatedInPeriod, 960000);
    const row = ledger.items.flatMap(group => group.payables).find(row => row.id === ap.id);
    assert.equal(row.paidAmount, 0); assert.equal(row.settledAmount, 960000);
    const id = result.payment.id;
    const document = await db.receivablePaymentDocument.create({ data: { paymentId: id, storageKey: randomUUID(), name: 'Acta ficticia.pdf', mimeType: 'application/pdf', size: 100, sha256: 'test' } });
    const review = await readOffset(db, id, actor);
    const reverse = { reason: 'El acuerdo se dejó sin efecto', expectedRevision: review.revision, requestId: randomUUID() };
    await assert.rejects(reverseReceivablePayment(db, id, { reason: 'Una sola parte' }, actor), { code: 'OFFSET_LINKED' });
    await assert.rejects(updateReceivablePayment(db, id, { amount: 900000, paidAt: '2026-09-18', reason: 'Corregir solo una parte' }, actor), { code: 'OFFSET_LINKED' });
    await assert.rejects(reversePayablePayment(db, result.payablePayment.id, 'Una sola parte', actor), { code: 'OFFSET_LINKED' });
    const undone = await reverseOffset(db, id, reverse, actor);
    assert.equal(undone.receivable.outstanding, 960000); assert.equal(undone.payable.outstanding, 1000000);
    assert.equal((await reverseOffset(db, id, reverse, actor)).replayed, true);
    assert.ok((await db.payablePayment.findUnique({ where: { id: result.payablePayment.id } })).reversedAt);
    assert.equal((await db.receivablePaymentDocument.findUnique({ where: { id: document.id } })).paymentId, id);
    assert.equal(await db.financialRecord.count(), 0);
    await assert.rejects(deleteReceivable(db, ar.id, 'Borrar después de revertir', actor), { code: 'OFFSET_HISTORY_PROTECTED' });
    await assert.rejects(db.receivablePayment.delete({ where: { id } }), { code: 'P2003' });
    await assert.rejects(createOffset(db, ar.id, input, actor), { statusCode: 409 });
  });
  await t.test('parcial y cierre mixto nunca se llaman pago en dinero', async () => {
    const { ar, ap, prepare } = await seed();
    await db.accountsPayable.update({ where: { id: ap.id }, data: { amount: 400000 } });
    const result = await createOffset(db, ar.id, await prepare(400000), actor);
    assert.equal(result.receivable.outstanding, 560000); assert.equal(result.payable.status, 'SALDADA');
  });
  await t.test('no acepta otro tercero, moneda sin conversión, saldo cambiado ni monto excesivo', async () => {
    const { ar, ap, party, prepare } = await seed(); const input = await prepare();
    await assert.rejects(createOffset(db, ar.id, { ...input, amount: 1000001 }, actor), { statusCode: 409 });
    await db.thirdParty.update({ where: { id: party.id }, data: { clientId: null } });
    await assert.rejects(createOffset(db, ar.id, input, actor), { statusCode: 409 });
    await db.thirdParty.update({ where: { id: party.id }, data: { clientId: ar.clientId } });
    await db.accountsReceivable.update({ where: { id: ar.id }, data: { currency: 'USD' } });
    await assert.rejects(createOffset(db, ar.id, input, actor), { statusCode: 409 });
    await db.accountsReceivable.update({ where: { id: ar.id }, data: { currency: 'COP', amount: 900000 } });
    await assert.rejects(createOffset(db, ar.id, input, actor), { statusCode: 409 });
    assert.equal(await db.payablePayment.count({ where: { payableId: ap.id } }), 0);
  });
  await t.test('relee permiso y períodos; un fallo de auditoría revierte ambos lados', async () => {
    const { ar, ap, prepare } = await seed(); const input = await prepare();
    const period = await db.financialPeriod.create({ data: { year: 2026, month: 9, status: 'CLOSED' } });
    await assert.rejects(createOffset(db, ar.id, input, actor), { statusCode: 409 });
    await db.financialPeriod.delete({ where: { id: period.id } });
    await db.user.update({ where: { id: actor.id }, data: { isActive: false } });
    await assert.rejects(createOffset(db, ar.id, input, actor), { statusCode: 403 });
    await db.user.update({ where: { id: actor.id }, data: { isActive: true } });
    const failing = { $transaction: (work, options) => db.$transaction(tx => work(new Proxy(tx, { get(target, key) { return key === 'financialAuditEvent' ? { ...target[key], create: async () => { throw new Error('historial fallido'); } } : target[key]; } })), options) };
    await assert.rejects(createOffset(failing, ar.id, input, actor), /historial fallido/);
    assert.equal(await db.payablePayment.count({ where: { payableId: ap.id } }), 0);
    assert.equal(await db.receivablePayment.count({ where: { receivableId: ar.id } }), 0);
  });
  await t.test('concurrencia: un solo cruce de la misma revisión', async () => {
    const { ar, ap, prepare } = await seed(); const input = await prepare(400000);
    const results = await Promise.allSettled([input, { ...input, requestId: randomUUID() }].map(body => createOffset(db, ar.id, body, actor)));
    assert.equal(results.filter(row => row.status === 'fulfilled').length, 1);
    assert.equal(results.find(row => row.status === 'rejected').reason.statusCode, 409);
    assert.equal(await db.payablePayment.count({ where: { payableId: ap.id } }), 1);
  });
  await t.test('reversión rechaza revisión vieja, permiso revocado, mes cerrado y guarda todo o nada', async () => {
    const { ar, ap, prepare } = await seed();
    const made = await createOffset(db, ar.id, await prepare(), actor);
    const id = made.payment.id;
    const input = { reason: 'Reversión de prueba', requestId: randomUUID(), expectedRevision: (await readOffset(db, id, actor)).revision };
    const payment = await payPayable(db, ap.id, { amount: 40000, paidAt: '2026-09-19', accountId: fixture.first.id }, actor);
    assert.equal(payment.payable.status, 'SALDADA');
    await assert.rejects(reverseOffset(db, id, input, actor), { statusCode: 409 });
    input.expectedRevision = (await readOffset(db, id, actor)).revision;
    const period = await db.financialPeriod.create({ data: { year: 2026, month: 9, status: 'CLOSED' } });
    await assert.rejects(reverseOffset(db, id, input, actor), { statusCode: 409 });
    await db.financialPeriod.delete({ where: { id: period.id } });
    await db.user.update({ where: { id: actor.id }, data: { isActive: false } });
    await assert.rejects(reverseOffset(db, id, input, actor), { statusCode: 403 });
    await db.user.update({ where: { id: actor.id }, data: { isActive: true } });
    const failing = { $transaction: (work, options) => db.$transaction(tx => work(new Proxy(tx, { get(target, key) { return key === 'financialAuditEvent' ? { ...target[key], create: async () => { throw new Error('historial fallido'); } } : target[key]; } })), options) };
    await assert.rejects(reverseOffset(failing, id, input, actor), /historial fallido/);
    assert.equal((await db.receivablePayment.findUnique({ where: { id } })).reversedAt, null);
    assert.equal((await db.payablePayment.findUnique({ where: { id: made.payablePayment.id } })).reversedAt, null);
    const results = await Promise.allSettled([input, { ...input, requestId: randomUUID() }].map(body => reverseOffset(db, id, body, actor)));
    assert.equal(results.filter(row => row.status === 'fulfilled').length, 1);
    assert.equal(results.find(row => row.status === 'rejected').reason.statusCode, 409);
    const current = await readOffset(db, id, actor);
    assert.equal(current.payable.outstanding, 960000);
    assert.equal((await db.financialRecord.findUnique({ where: { id: payment.financialRecord.id } })).status, 'POSTED');
    assert.equal(current.history.length, 2);
  });
  await t.test('legado y soportes siguen intactos; ningún ajuste de texto se vuelve cruce', async () => {
    const { ar, ap, prepare } = await seed();
    const legacy = await db.receivablePayment.create({ data: { receivableId: ar.id, kind: 'COMPENSACION', amount: 100000, paidAt: new Date('2026-09-10'), detail: { offsetAgainst: 'Descripción antigua', authorizedBy: 'Dirección' } } });
    const made = await createOffset(db, ar.id, await prepare(860000), actor);
    assert.equal(made.payable.outstanding, 140000);
    await reverseReceivablePayment(db, legacy.id, { reason: 'Reversión de la anotación antigua' }, actor);
    assert.equal((await readOffset(db, made.payment.id, actor)).payable.outstanding, 140000);
    assert.equal(await db.payablePayment.count({ where: { payableId: ap.id } }), 1);
    const reader = await db.user.create({ data: { name: 'Lector', email: `${randomUUID()}@example.invalid`, password: 'fixture', role: 'VIEWER', financialRole: 'VIEWER', modulePermissions: { financiero: true } } });
    const view = await readOffset(db, made.payment.id, reader);
    assert.equal(view.canReverse, false); assert.deepEqual(view.history, []);
    await assert.rejects(createOffset(db, ar.id, await prepare(100), reader), { statusCode: 403 });
    const cash = await db.payablePayment.create({ data: { payableId: ap.id, amount: 1, paidAt: new Date('2026-09-18') } });
    assert.equal(cash.kind, 'PAGO'); assert.equal(cash.offsetReceivablePaymentId, null);
    await assert.rejects(db.payablePayment.create({ data: { payableId: ap.id, kind: 'COMPENSACION', amount: 1, paidAt: new Date('2026-09-18') } }));
  });
});
