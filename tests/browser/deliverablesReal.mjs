import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright-core';
import sharp from 'sharp';

test('aplicación real: carrusel y entrega interna, orden y sustitución íntegra con historial', async () => {
  const access = JSON.parse(await readFile('output/task-piece-local/preview-access.json', 'utf8'));
  const origin = 'http://127.0.0.1:3183';
  assert.equal(access.apiOrigin, 'http://127.0.0.1:8092');
  assert.equal((await fetch(`${origin}/api/health`).then(r => r.json())).isolatedTaskPieceTest, true);
  const output = path.resolve('output/task-piece-delivery/walkthrough');
  await mkdir(output, { recursive: true });
  const files = [];
  for (const [index, color, label] of [[1, '#173c47', 'Primera lámina'], [2, '#306d61', 'Segunda lámina'], [3, '#173c47', 'Entrega corregida']]) {
    const file = path.join(output, `${index === 3 ? 'correccion' : `lamina-${index}`}.png`);
    await sharp(Buffer.from(`<svg width="900" height="900" xmlns="http://www.w3.org/2000/svg"><rect width="900" height="900" fill="${color}"/><circle cx="720" cy="180" r="70" fill="#fcd200"/><text x="90" y="410" font-family="Arial" font-size="90" font-weight="bold" fill="white">FARO</text><text x="90" y="500" font-family="Arial" font-size="38" fill="white">${label}</text><text x="90" y="800" font-family="Arial" font-size="24" fill="white">PRUEBA LOCAL · DATOS FICTICIOS</text></svg>`)).png().toFile(file);
    files.push(file);
  }
  // Small valid one-page PDF for the existing viewer, generated solely for this acceptance.
  const pdfParts = ['%PDF-1.4\n']; const offsets = [0];
  const objects = ['<< /Type /Catalog /Pages 2 0 R >>', '<< /Type /Pages /Kids [3 0 R] /Count 1 >>', '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R >>', '<< /Length 0 >>\nstream\n\nendstream'];
  objects.forEach((body, i) => { offsets.push(Buffer.byteLength(pdfParts.join(''))); pdfParts.push(`${i + 1} 0 obj\n${body}\nendobj\n`); });
  const xref = Buffer.byteLength(pdfParts.join(''));
  pdfParts.push(`xref\n0 5\n0000000000 65535 f \n${offsets.slice(1).map(offset => `${String(offset).padStart(10, '0')} 00000 n \n`).join('')}trailer\n<< /Size 5 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`);
  const pdf = path.join(output, 'propuesta.pdf'); await writeFile(pdf, pdfParts.join(''));
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(20000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const piece = access.pieces.current.approved;
  const shot = async name => { await page.evaluate(() => document.fonts.ready); await page.screenshot({ path: path.join(output, name), fullPage: false, animations: 'disabled' }); };
  try {
    await page.goto(`${origin}/gestion?taskId=${piece.taskId}`);
    await page.locator('input[type="email"]').fill(access.users.ana.email);
    await page.locator('input[type="password"]').fill(access.users.ana.password);
    await page.getByRole('button', { name: 'Acceder', exact: true }).click();
    await page.getByRole('button', { name: 'Entendido', exact: true }).click();
    await page.getByRole('button', { name: 'Ver pieza', exact: true }).waitFor();
    const token = await page.evaluate(() => localStorage.getItem('authToken'));
    const get = async route => { const response = await fetch(`${origin}/api${route}`, { headers: { Authorization: `Bearer ${token}` } }); assert.equal(response.status, 200); return response.json(); };
    const before = await get(`/tasks/${piece.taskId}`);
    await page.getByRole('button', { name: 'Ver pieza', exact: true }).click();
    const peek = page.locator('[data-piece-peek]');
    await peek.getByRole('button', { name: /^(Entregar pieza|Actualizar entrega)$/ }).waitFor();
    const [chooser] = await Promise.all([page.waitForEvent('filechooser'), peek.getByRole('button', { name: /^(Entregar pieza|Actualizar entrega)$/ }).click()]);
    assert.equal(chooser.isMultiple(), true); await chooser.setFiles(files.slice(0, 2));
    await peek.locator('[data-final-asset-tile]').nth(1).waitFor();
    await peek.getByRole('button', { name: 'Actualizar entrega', exact: true }).waitFor({ state: 'visible' });
    const initial = await get(`/content/items/${piece.id}/delivery`);
    assert.equal(initial.files.length, 2);
    const ordered = page.waitForResponse(response => response.url().endsWith('/final-assets/order') && response.request().method() === 'PUT');
    await peek.locator('[data-final-asset-grip]').first().focus(); await page.keyboard.press('ArrowRight');
    assert.equal((await ordered).status(), 200);
    assert.deepEqual((await get(`/content/items/${piece.id}/delivery`)).files.map(file => file.id), initial.files.map(file => file.id).reverse());
    await shot('01-carrusel-ordenado.png');
    await page.getByLabel('Archivos de la pieza final').setInputFiles(files[2]);
    await peek.locator('[data-final-asset-tile]').getByText('correccion.png', { exact: true }).waitFor();
    assert.equal(await peek.locator('[data-final-asset-tile]').count(), 1);
    const saved = await get(`/content/items/${piece.id}/delivery`);
    assert.equal(saved.files.length, 1); assert.equal(saved.history[0].action, 'REPLACED');
    await peek.locator('summary').filter({ hasText: 'Historial de entregas' }).click();
    await peek.getByText('Conjunto anterior', { exact: true }).first().waitFor();
    await shot('02-pieza-actualizada-historial.png');
    const after = await get(`/tasks/${piece.taskId}`);
    assert.equal(after.status, before.status); assert.deepEqual(after.participants, before.participants);
    await peek.getByRole('button', { name: 'Cerrar pieza', exact: true }).click();
    await page.getByRole('button', { name: 'Abrir Parrilla', exact: true }).click();
    await page.locator(`#item-${piece.id}`).getByText('correccion.png', { exact: true }).waitFor();
    assert.deepEqual((await get(`/content/plans/${piece.planId}`)).items.find(item => item.id === piece.id).finalAssets.map(file => file.id), saved.files.map(file => file.id));
    await page.goto(`${origin}/gestion?taskId=${access.standaloneTask.id}`);
    const section = page.getByRole('region', { name: 'Entregables de la tarea', exact: true });
    await section.getByLabel('Archivos del entregable').waitFor({ state: 'attached' });
    const taskBefore = await get(`/tasks/${access.standaloneTask.id}`);
    await section.getByLabel('Archivos del entregable').setInputFiles([files[0], pdf]);
    await section.locator('[data-final-asset-tile]').nth(1).waitFor();
    await section.getByRole('status').getByText('Entrega guardada', { exact: true }).waitFor();
    const standaloneBase = `/tasks/${access.standaloneTask.id}/deliverables`;
    const internal = await get(standaloneBase); assert.equal(internal.files.length, 2);
    const taskOrdered = page.waitForResponse(response => response.url().endsWith('/deliverables/order') && response.request().method() === 'PUT');
    await section.locator('[data-final-asset-grip]').first().focus(); await page.keyboard.press('ArrowRight');
    assert.equal((await taskOrdered).status(), 200);
    await section.getByRole('status').getByText('Orden guardado', { exact: true }).waitFor();
    const download = page.waitForEvent('download'); await section.getByRole('button', { name: 'Descargar propuesta.pdf', exact: true }).click();
    assert.equal((await download).suggestedFilename(), 'propuesta.pdf');
    await shot('03-entrega-interna-imagen-pdf.png');
    await section.getByRole('button', { name: 'Ver propuesta.pdf', exact: true }).click();
    const pdfViewer = page.getByRole('dialog', { name: 'propuesta.pdf', exact: true });
    await pdfViewer.locator('canvas[aria-label="propuesta.pdf, página 1"]').waitFor();
    await page.waitForFunction(() => {
      const canvas = document.querySelector('canvas[aria-label="propuesta.pdf, página 1"]');
      return canvas?.width > 600 && canvas.height > 700;
    });
    assert.equal(await pdfViewer.getByRole('alert').count(), 0);
    await shot('03b-vista-pdf.png');
    await pdfViewer.getByRole('button', { name: 'Cerrar vista previa', exact: true }).click();
    assert.equal(await page.locator('[data-task-panel-content]').isVisible(), true);

    // Drive is a projection of these exact native files, with their original access rules.
    const driveRead = await get(`/drive/contents?folderId=deliverables&query=${encodeURIComponent(access.client.name)}`);
    const drivePdf = driveRead.files.find(file => file.source?.taskId === access.standaloneTask.id && file.originalName === 'propuesta.pdf');
    assert.ok(drivePdf, 'Drive incluye el PDF vigente de esta tarea, sin copiarlo a un archivo manual');
    assert.equal(drivePdf.fileId, internal.files.find(file => file.name === 'propuesta.pdf').id);
    assert.equal(driveRead.files.some(file => file.source?.itemId === piece.id && file.fileId === saved.files[0].id), true);
    await page.goto(`${origin}/drive?folderId=deliverables`);
    await page.getByText(access.client.name, { exact: true }).click();
    await page.getByRole('button', { name: /^2026(?:\s|$)/ }).click();
    await page.getByRole('button', { name: /^Noviembre(?:\s|$)/ }).click();
    await page.getByRole('button', { name: /^Tareas(?:\s|$)/ }).click();
    await page.getByText(access.standaloneTask.title, { exact: true }).click();
    const driveFolderId = new URL(page.url()).searchParams.get('folderId');
    await page.getByRole('button', { name: `Ver ${drivePdf.name}`, exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: /^(Nueva carpeta|Subir archivos)$/ }).count(), 0);
    assert.equal(await page.getByRole('button', { name: /^(Renombrar |Mover a raíz|Enviar .* a papelera)/ }).count(), 0);
    const driveDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: `Descargar ${drivePdf.name}`, exact: true }).click();
    assert.equal((await driveDownload).suggestedFilename(), drivePdf.downloadName);
    await page.getByRole('button', { name: `Ver ${drivePdf.name}`, exact: true }).click();
    const driveViewer = page.getByRole('dialog', { name: drivePdf.name, exact: true });
    await driveViewer.locator('canvas').waitFor();
    await page.waitForFunction(() => document.querySelector('[role="dialog"] canvas')?.width > 600);
    assert.equal(await driveViewer.getByRole('alert').count(), 0);
    await shot('06-pdf-en-drive.png');
    await driveViewer.getByRole('button', { name: 'Cerrar visor', exact: true }).click();
    const drivePdfCard = page.locator('article').filter({ has: page.getByRole('button', { name: `Ver ${drivePdf.name}`, exact: true }) });
    await drivePdfCard.getByRole('button', { name: 'Abrir tarea', exact: true }).click();
    await page.locator('[data-task-panel-content]').waitFor();
    await page.locator('[data-task-panel-content]').getByRole('button', { name: 'Cerrar', exact: true }).first().click();
    await page.getByRole('button', { name: /Volver a Drive/ }).click();
    await page.getByRole('button', { name: `Ver ${drivePdf.name}`, exact: true }).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('folderId'), driveFolderId);
    await shot('07-entregables-drive.png');
    await drivePdfCard.getByRole('button', { name: 'Abrir tarea', exact: true }).click();
    await section.getByRole('button', { name: 'Actualizar entrega', exact: true }).waitFor();
    await section.getByLabel('Archivos del entregable').setInputFiles([files[2], pdf]);
    await section.locator('[data-final-asset-tile]').getByText('correccion.png', { exact: true }).waitFor();
    assert.equal(await section.locator('[data-final-asset-tile]').count(), 2);
    await section.locator('summary').filter({ hasText: 'Historial de entregas' }).click();
    const taskAfter = await get(`/tasks/${access.standaloneTask.id}`);
    assert.equal(taskAfter.status, taskBefore.status); assert.deepEqual(taskAfter.participants, taskBefore.participants);
    const lastInternal = await get(standaloneBase); assert.equal(lastInternal.files.length, 2); assert.equal(lastInternal.history[0].action, 'REPLACED');
    assert.equal(lastInternal.files.some(file => internal.files.some(old => old.id === file.id)), false, 'actualizar sustituye el conjunto incluso cuando un nombre se repite');
    const updatedDrive = await get(`/drive/contents?folderId=${encodeURIComponent(driveFolderId)}`);
    assert.deepEqual(updatedDrive.files.map(file => file.fileId), lastInternal.files.map(file => file.id));
    assert.equal(updatedDrive.files.some(file => file.originalName === 'lamina-1.png'), false);
    await shot('04-entrega-interna-actualizada.png');
    await page.evaluate(() => document.documentElement.classList.add('dark'));
    await page.setViewportSize({ width: 390, height: 844 });
    await section.getByRole('button', { name: 'Actualizar entrega', exact: true }).scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true);
    await shot('05-entrega-interna-movil-oscuro.png');

    // Manual folders stay writable, separate from the automatic delivery projection.
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`${origin}/drive`);
    await page.getByRole('button', { name: 'Nueva carpeta', exact: true }).click();
    const newFolder = page.getByRole('dialog', { name: 'Nueva carpeta', exact: true });
    const manualFolderName = `Material Faro ${access.runId.slice(0, 8)} ${Date.now().toString(36)}`;
    await newFolder.getByRole('textbox', { name: 'Nombre', exact: true }).fill(manualFolderName);
    await newFolder.getByPlaceholder('Qué guarda esta carpeta').fill('Archivos de prueba local, creados desde Drive.');
    await newFolder.getByRole('button', { name: 'Crear carpeta', exact: true }).click();
    await page.getByText(manualFolderName, { exact: true }).click();
    const [manualChooser] = await Promise.all([page.waitForEvent('filechooser'), page.getByRole('button', { name: 'Subir archivos', exact: true }).click()]);
    await manualChooser.setFiles(pdf);
    await page.getByRole('button', { name: 'Ver propuesta.pdf', exact: true }).waitFor();
    const manualFolder = (await get('/drive/contents')).folders.find(folder => folder.name === manualFolderName);
    assert.ok(manualFolder && !manualFolder.system);
    const manualFiles = (await get(`/drive/contents?folderId=${encodeURIComponent(manualFolder.id)}`)).files;
    assert.equal(manualFiles.length, 1); assert.equal(manualFiles[0].kind, 'UPLOAD'); assert.equal(manualFiles[0].name, 'propuesta.pdf');
    await page.getByRole('button', { name: 'Ver propuesta.pdf', exact: true }).click();
    const manualViewer = page.getByRole('dialog', { name: 'propuesta.pdf', exact: true });
    await manualViewer.locator('canvas').waitFor();
    assert.equal(await manualViewer.getByRole('alert').count(), 0);
    await manualViewer.getByRole('button', { name: 'Cerrar visor', exact: true }).click();
    await shot('09-carpeta-manual-drive.png');

    const drivePath = `/drive?folderId=${encodeURIComponent(driveFolderId)}`;
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${origin}${drivePath}`);
    await page.getByRole('button', { name: `Ver ${updatedDrive.files[0].name}`, exact: true }).waitFor();
    await page.evaluate(() => document.documentElement.classList.add('dark'));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true);
    assert.equal(await page.locator('article').evaluateAll(cards => cards.every(card => card.getBoundingClientRect().right <= card.closest('section').getBoundingClientRect().right)), true);
    await shot('08-drive-movil-oscuro.png');
    assert.deepEqual(errors, []);
    await writeFile(path.join(output, 'verification.json'), JSON.stringify({ piece: piece.id, standaloneTask: access.standaloneTask.id, sameParrillaDelivery: true, oldSetsReplaced: true, orderPersisted: true, personalStatesUnchanged: true, pdfDownload: true, pdfPreview: true, pdfPages: 1, driveNativeFiles: true, drivePdfPreview: true, driveNamedDownload: true, driveOriginReturn: true, driveCurrentFilesOnly: true, driveManualFolder: manualFolder.id, driveManualUpload: true, drivePath, pageErrors: errors }, null, 2));
  } catch (error) { await shot('error.png'); throw error; }
  finally { await browser.close(); }
});
