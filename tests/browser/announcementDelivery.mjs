import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

test('anuncio en banda y vista previa sin navegación; cerrar no registra apertura', async () => {
  const module = await import('../../scripts/preview-announcement-delivery.mjs').catch(() => null);
  assert.ok(module, 'La muestra debe utilizar los componentes y servicios reales');
  const preview = await module.createAnnouncementPreview({ port: 0 });
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(`${preview.origin}/gestion?estado=pendiente`);
    await page.getByLabel('Nota en edición').fill('Conservar mi borrador');
    const band = page.locator('[data-important-notice]'); await band.waitFor();
    await page.screenshot({ animations: 'disabled', path: 'output/announcement-band.png' });
    const before = page.url();
    await band.getByRole('button', { name: 'Ver anuncio', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Anuncio general', exact: true }); await dialog.waitFor();
    await page.waitForFunction(async () => (await (await fetch('/api/preview/state')).json()).deliveries.some(d => d.userId === 'demo-reader' && d.openedAt));
    assert.equal(page.url(), before);
    assert.match(await dialog.innerText(), /Prioridades/);
    await page.screenshot({ animations: 'disabled', path: 'output/announcement-preview.png' });
    await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
    assert.equal(await page.getByLabel('Nota en edición').inputValue(), 'Conservar mi borrador');
    await page.reload(); assert.equal(await band.count(), 0);
    await page.getByRole('button', { name: 'Nuevo ejemplo', exact: true }).click(); await band.waitFor();
    await band.getByRole('button', { name: 'Cerrar', exact: true }).click(); await band.waitFor({ state: 'detached' });
    let state = await page.evaluate(async () => (await fetch('/api/preview/state')).json());
    const closed = state.deliveries.find(d => d.userId === 'demo-reader' && d.dismissedAt);
    assert.ok(closed); assert.equal(closed.openedAt, null);
    await page.reload(); assert.equal(await band.count(), 0);
    await page.getByRole('button', { name: 'Nuevo ejemplo', exact: true }).click(); await band.waitFor();
    await page.route('**/api/dashboard/announcements/*/response', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'No se pudo guardar la respuesta.' }) }));
    await band.getByRole('button', { name: 'Cerrar', exact: true }).click();
    await page.getByText('No se pudo guardar la respuesta.', { exact: true }).waitFor();
    assert.ok(await band.isVisible());
    await page.unroute('**/api/dashboard/announcements/*/response');
    await page.getByText('No se pudo guardar la respuesta.', { exact: true }).waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Tema oscuro', exact: true }).click();
    await page.screenshot({ animations: 'disabled', path: 'output/announcement-dark.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok((await band.boundingBox()).width <= 390);
    await page.screenshot({ animations: 'disabled', path: 'output/announcement-mobile.png' });
    await band.getByRole('button', { name: 'Ver anuncio', exact: true }).click(); await dialog.waitFor();
    await dialog.getByRole('heading', { name: 'Anuncio general', exact: true }).click();
    await page.mouse.click(2, 2); await dialog.waitFor({ state: 'detached' });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: 'Tema claro', exact: true }).click();
    await page.getByRole('button', { name: 'Ver como emisor', exact: true }).click();
    await page.getByRole('button', { name: 'Ver como destinataria', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Ver historial de anuncios', exact: true }).click();
    await page.getByRole('button', { name: 'Ver respuestas', exact: true }).first().click();
    const responses = page.getByRole('dialog', { name: 'Respuestas del anuncio', exact: true }); await responses.waitFor();
    await responses.getByText('Camila · muestra', { exact: true }).waitFor();
    assert.match(await responses.innerText(), /Abrió el anuncio/);
    await page.screenshot({ animations: 'disabled', path: 'output/announcement-responses.png' });
    await page.keyboard.press('Escape'); await responses.waitFor({ state: 'detached' });
    await page.getByRole('button', { name: 'Ver anuncio', exact: true }).last().click(); await dialog.waitFor();
    assert.ok(Number(await dialog.evaluate(e => getComputedStyle(e).zIndex)) >= 140);
    await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
    await page.getByRole('button', { name: 'Archivar anuncio', exact: true }).last().click();
    const archive = page.getByRole('dialog', { name: 'Archivar anuncio', exact: true }); await archive.waitFor();
    await archive.getByRole('button', { name: 'Archivar anuncio', exact: true }).click(); await archive.waitFor({ state: 'detached' });
    await page.getByText('Archivado', { exact: true }).waitFor();
    await page.screenshot({ animations: 'disabled', path: 'output/announcement-archived.png' });
    state = await page.evaluate(async () => (await fetch('/api/preview/state')).json());
    assert.equal(state.announcements.length, 3, 'archivar conserva el anuncio');
    await page.getByRole('button', { name: 'Nuevo anuncio', exact: true }).click();
    await page.locator('[contenteditable="true"]').fill('Nueva jornada de producción. Revisaremos los horarios el lunes.');
    await page.getByRole('button', { name: 'Publicar anuncio', exact: true }).click();
    await page.waitForFunction(async () => (await (await fetch('/api/preview/state')).json()).announcements.length === 4);
    const newCard = page.locator('article').filter({ hasText: 'Nueva jornada de producción.' }).last();
    await newCard.getByRole('button', { name: 'Editar anuncio', exact: true }).click();
    await page.locator('[contenteditable="true"]').fill('Nueva jornada de producción. Revisaremos los horarios el martes.');
    await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
    await page.waitForFunction(async () => (await (await fetch('/api/preview/state')).json()).announcements.some(a => a.content.includes('horarios el martes') && a.revision === 2));
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await preview.close(); }
});
