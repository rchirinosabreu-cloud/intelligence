import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { chooseOption } from './selectHelpers.mjs';
const base = process.env.BARTER_PREVIEW_URL || 'http://127.0.0.1:3850';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.setDefaultTimeout(20000);
  await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.getByRole('tab', { name: 'Cuentas por cobrar', exact: true }).click();
  await page.getByRole('button', { name: /Nuva · ejemplo ficticio/ }).click();
  await page.getByRole('button', { name: 'Saldar de otra forma', exact: true }).click();
  await chooseOption(page.getByRole('combobox', { name: 'Forma de saldar' }), 'CANJE');
  const dialog = page.locator('[data-financial-barter]');
  await dialog.getByLabel('Valor recibido').fill('900000');
  await dialog.getByLabel('Fecha del canje').fill('07/11/2026'); await dialog.getByLabel('Fecha del canje').press('Tab');
  await dialog.getByLabel('Bienes o servicios recibidos').fill('Mobiliario entregado al beneficiario · muestra ficticia');
  await chooseOption(dialog.getByRole('combobox', { name: 'Destino', exact: true }), 'BENEFICIARIO');
  await chooseOption(dialog.getByRole('combobox', { name: /Beneficiario en Terceros/ }), 'demo-beneficiary');
  await dialog.getByLabel('Autorizado por').fill('Dirección · ejemplo local');
  await dialog.getByLabel('Motivo', { exact: true }).fill('Entrega al beneficiario con reintegro autorizado; importes ficticios.');
  await dialog.getByRole('button', { name: 'Revisar canje y destino' }).click();
  assert.match(await dialog.innerText(), /600\.000/);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'output/barter-review.png', animations: 'disabled' });
  let lost = false;
  await page.route('**/preview-api/receivables/barter-ar/settlements', async route => {
    if (lost) return route.continue(); lost = true;
    const response = await route.fetch(); assert.equal(response.status(), 201);
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Respuesta perdida de muestra. Reintenta sin duplicar.' }) });
  });
  await dialog.getByRole('button', { name: 'Confirmar canje y destino' }).click();
  await dialog.getByRole('alert').waitFor();
  await dialog.getByRole('button', { name: 'Confirmar canje y destino' }).click();
  await dialog.getByRole('heading', { name: 'Detalle del canje' }).waitFor();
  await dialog.locator('summary').click();
  await page.screenshot({ path: 'output/barter-saved.png', animations: 'disabled' });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: /Francisco · ejemplo ficticio/ }).click();
  await page.getByRole('button', { name: 'Ver canje de origen' }).waitFor();
  await page.getByRole('button', { name: /Francisco · ejemplo ficticio/ }).evaluate(el => el.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: 'output/barter-beneficiary.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Ver canje de origen' }).click();
  await dialog.getByLabel('Motivo de reversión').fill('Entrega anulada; se conserva el registro original.');
  await dialog.getByRole('button', { name: 'Revisar reversión' }).click();
  assert.match(await dialog.innerText(), /1\.500\.000/);
  assert.match(await dialog.innerText(), /saldo \$0/);
  await page.screenshot({ path: 'output/barter-reversal-review.png', animations: 'disabled' });
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await page.screenshot({ path: 'output/barter-dark.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await page.screenshot({ path: 'output/barter-mobile.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.evaluate(() => document.documentElement.classList.remove('dark'));
  await dialog.getByRole('button', { name: 'Confirmar reversión' }).click();
  await dialog.getByRole('heading', { name: 'Canje revertido' }).waitFor();
  await dialog.locator('summary').click();
  await page.screenshot({ path: 'output/barter-reversed.png', animations: 'disabled' });
  assert.match(await dialog.innerText(), /Historial del canje \(2\)/);
  const records = await (await page.request.get(`${base}/preview-api/records`)).json(); assert.equal(records.total, 0);
  assert.deepEqual(errors, []);
  console.log('Canje y beneficiario en Cartera, respuesta perdida, reversión, historial y claro/oscuro/móvil: OK.');
} finally { await browser.close(); }
