import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';

test('app real: cambiar fecha lleva a la nueva parrilla; enlaces, Kanban y Drive siguen la pieza; vuelta en móvil', async () => {
  const access = JSON.parse(await readFile('output/content-period-transfer/access.json', 'utf8'));
  assert.equal(access.origin, 'http://127.0.0.1:3183');
  assert.equal((await fetch(`${access.origin}/api/health`).then(r => r.json())).isolatedTaskPieceTest, true);
  const piece = access.pieces.previous.approved;
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(20000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await mkdir('output/content-period-transfer/screenshots', { recursive: true });
  try {
    await page.goto(`${access.origin}/parrillas/${piece.planId}?item=${piece.id}`);
    await page.locator('input[type=email]').fill(access.users.ana.email);
    await page.locator('input[type=password]').fill(access.users.ana.password);
    await page.getByRole('button', { name: 'Acceder', exact: true }).click();
    const date = () => page.locator(`#item-${piece.id} .react-datepicker__input-container input`).first();
    await date().waitFor();
    const change = async value => {
      const response = page.waitForResponse(r => r.url().endsWith(`/content/items/${piece.id}`) && r.request().method() === 'PATCH');
      await date().fill(value); await date().press('Tab');
      const saved = await response; assert.equal(saved.status(), 200, await saved.text()); return saved.json();
    };
    const token = await page.evaluate(() => localStorage.getItem('authToken'));
    const get = async route => { const r = await fetch(`${access.origin}/api${route}`, { headers: { Authorization: `Bearer ${token}` } }); assert.equal(r.status, 200); return r.json(); };
    const before = await get(`/content/items/${piece.id}/delivery`);
    const moved = await change('01/01/2031');
    assert.ok(moved.periodTransfer); assert.notEqual(moved.planId, piece.planId);
    await page.waitForURL(`**/parrillas/${moved.planId}?item=${piece.id}`);
    await date().waitFor();
    assert.equal(await date().inputValue(), '01/01/2031');
    await page.screenshot({ path: 'output/content-period-transfer/screenshots/01-mes-destino.png', animations: 'disabled' });
    assert.deepEqual((await get(`/content/items/${piece.id}/delivery`)).files.map(f => f.id), before.files.map(f => f.id));
    assert.equal((await get(`/tasks/${piece.taskId}`)).contentItem.planId, moved.planId);
    const drive = await get('/drive/contents?folderId=deliverables&query=entrega-original');
    assert.equal(drive.files.find(f => f.source.itemId === piece.id).source.planId, moved.planId);
    const originalPlan = access.plans.find(plan => plan.id === piece.planId);
    const oldFolder = 'deliverables:' + Buffer.from(JSON.stringify([access.client.id, originalPlan.year, originalPlan.month, 'CONTENT', piece.id])).toString('base64url');
    const newFolder = 'deliverables:' + Buffer.from(JSON.stringify([access.client.id, 2031, 1, 'CONTENT', piece.id])).toString('base64url');
    await page.goto(`${access.origin}/drive?folderId=${encodeURIComponent(oldFolder)}&q=entrega-original`);
    await page.waitForURL(url => url.searchParams.get('folderId') === newFolder && url.searchParams.get('q') === 'entrega-original');
    await page.getByRole('button', { name: 'Enero', exact: true }).waitFor();
    await page.getByRole('button', { name: `Ver ${drive.files.find(f => f.source.itemId === piece.id).name}`, exact: true }).waitFor();
    await page.screenshot({ path: 'output/content-period-transfer/screenshots/03-drive-reubicado.png', animations: 'disabled' });
    await page.goto(`${access.origin}/parrillas/${piece.planId}?item=${piece.id}&view=calendar`);
    await page.waitForURL(`**/parrillas/${moved.planId}?item=${piece.id}&view=calendar`);
    await page.goto(`${access.origin}/parrillas/${moved.planId}?item=${piece.id}`);
    await date().waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => localStorage.setItem('theme', 'dark'));
    await page.reload(); await date().waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.classList.contains('dark')), true);
    const original = new Date(piece.publishDate);
    const originalDay = `${String(original.getUTCDate()).padStart(2, '0')}/${String(original.getUTCMonth() + 1).padStart(2, '0')}/${original.getUTCFullYear()}`;
    const returned = await change(originalDay);
    assert.equal(returned.planId, piece.planId); assert.equal(returned.periodTransfer.sourceRemoved, true);
    await page.waitForURL(`**/parrillas/${piece.planId}?item=${piece.id}`);
    await date().waitFor();
    await date().scrollIntoViewIfNeeded();
    await page.evaluate(() => scrollBy(0, -100));
    await page.screenshot({ path: 'output/content-period-transfer/screenshots/02-regreso-movil-oscuro.png', animations: 'disabled' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
