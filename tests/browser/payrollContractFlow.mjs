import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.PAYROLL_FLOW_URL || 'http://127.0.0.1:3864';
await mkdir('output/payroll-contract-flow', { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name:'Nómina', exact:true }).waitFor();
  const rodny = page.locator('tbody tr').filter({ hasText:'Rodny · muestra local' }).first();
  assert.match(await rodny.innerText(), /Contrato:/);
  assert.match(await rodny.innerText(), /Mensual registrado/);
  assert.doesNotMatch(await rodny.innerText(), /Fechas del servicio por precisar/);
  await page.getByRole('button', { name:'Generar nómina',exact:true }).click();
  await page.getByRole('button', { name:'Generar borradores',exact:true }).click();
  await page.getByText('Se creó 1 borrador.').waitFor();
  const jesu = page.locator('tbody tr').filter({ hasText:'Jesu · muestra local' });
  assert.equal(await jesu.count(),2);
  assert.match(await jesu.allInnerTexts().then(a=>a.join(' ')),/750[.,]000/);
  await page.screenshot({ path:'output/payroll-contract-flow/nomina.png',fullPage:true });
  await rodny.getByRole('button',{name:'Editar contrato',exact:true}).click();
  const editor = page.getByRole('dialog');
  await editor.getByLabel('Salario base mensual').fill('4500000');
  await editor.getByRole('button',{name:'Guardar y revisar nómina',exact:true}).click();
  const periods = page.locator('[data-payroll-periods]');
  await periods.getByRole('heading',{name:'Revisa antes de confirmar',exact:true}).waitFor({timeout:3000});
  assert.match(await periods.innerText(),/4[.,]808[.,]300/);
  assert.match(await periods.innerText(),/5[.,]008[.,]300/);
  await page.screenshot({path:'output/payroll-contract-flow/revisar-contrato.png'});
  await periods.getByRole('button',{name:'Confirmar',exact:true}).click();
  await periods.getByText('Período guardado.',{exact:true}).waitFor();
  await page.screenshot({path:'output/payroll-contract-flow/periodos.png'});
  await page.keyboard.press('Escape');
  assert.match(await rodny.innerText(),/5[.,]008[.,]300/);
  await page.getByRole('button', { name:'Generar nómina',exact:true }).click();
  await page.getByRole('button', { name:'Generar borradores',exact:true }).click();
  await page.getByText(/No se crearon borradores/).waitFor();
  assert.equal(await jesu.count(),2);
  await page.evaluate(()=>document.documentElement.classList.add('dark'));
  await page.screenshot({path:'output/payroll-contract-flow/nomina-oscuro.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/payroll-contract-flow/nomina-movil.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Recorrido real: contrato, generación, revisión del borrador, historial y reintento verificados.');
} finally { await browser.close(); }
