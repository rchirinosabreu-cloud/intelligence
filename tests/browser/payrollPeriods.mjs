import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(12000);
  await page.goto('http://127.0.0.1:3849/tests/fixtures/payroll-periods.html?year=2026&month=10&tab=nomina', { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.getByRole('button', { name: 'Períodos de Jesu · ejemplo local', exact: true }).click();
  const dialog = page.locator('[data-payroll-periods]');
  await dialog.getByRole('button', { name: 'Precisar fechas' }).click();
  await dialog.getByLabel('Inicio del servicio').fill('16/09/2026'); await dialog.getByLabel('Inicio del servicio').press('Tab');
  await dialog.getByLabel('Fin del servicio').fill('15/10/2026'); await dialog.getByLabel('Fin del servicio').press('Tab');
  await dialog.getByLabel('Motivo').fill('Fechas ilustrativas del período anterior, sin alterar su pago.');
  await dialog.getByRole('button', { name: 'Revisar', exact: true }).click();
  await dialog.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await dialog.getByRole('button', { name: 'Nuevo período', exact: true }).click();
  await dialog.getByLabel('Motivo').fill('Borrador que se conserva al cerrar.');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Períodos de Jesu · ejemplo local', exact: true }).click();
  await dialog.getByRole('button', { name: 'Nuevo período', exact: true }).click();
  assert.equal(await dialog.getByLabel('Motivo').inputValue(), 'Borrador que se conserva al cerrar.');
  await dialog.getByLabel('Inicio del servicio').fill('16/10/2026'); await dialog.getByLabel('Inicio del servicio').press('Tab');
  await dialog.getByLabel('Fin del servicio').fill('31/10/2026'); await dialog.getByLabel('Fin del servicio').press('Tab');
  await dialog.getByLabel('Valor del servicio').fill('750000');
  await dialog.getByLabel('Motivo').fill('Nuevo tramo acordado · ejemplo local.');
  await dialog.getByRole('button', { name: 'Revisar', exact: true }).click();
  await page.screenshot({ path: 'output/payroll-period-review.png', animations: 'disabled' });
  await dialog.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await dialog.getByText('Período guardado.').waitFor();
  await page.screenshot({ path: 'output/payroll-period-saved.png', animations: 'disabled' });
  assert.match(await dialog.innerText(), /750\.000/);
  await dialog.locator('article').filter({ hasText: 'Borrador' }).getByRole('button', { name: 'Revertir período', exact: true }).click();
  await dialog.getByLabel('Motivo').fill('Revertir el tramo de muestra, conservando el anterior.');
  await dialog.getByRole('button', { name: 'Revisar', exact: true }).click();
  await page.screenshot({ path: 'output/payroll-period-reversal-review.png', animations: 'disabled' });
  await dialog.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await dialog.getByText('Período revertido.').waitFor();
  await page.screenshot({ path: 'output/payroll-period-reversed.png', animations: 'disabled' });
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).first().click();
  await page.getByRole('button', { name: 'Descuentos de Melissa · ejemplo local', exact: true }).click();
  const deduction = page.locator('[data-payroll-deductions]');
  await deduction.getByRole('button', { name: /Melissa · préstamo ficticio/ }).click();
  await deduction.getByLabel('Valor del descuento').fill('300000');
  await deduction.getByLabel('Autorizado por').fill('Autorización de muestra');
  await deduction.getByLabel('Motivo').fill('Cuota acordada · demostración.');
  await deduction.getByLabel(/Confirmo que este préstamo/).check();
  await deduction.getByRole('button', { name: 'Revisar', exact: true }).click();
  await page.screenshot({ path: 'output/payroll-loan-review.png', animations: 'disabled' });
  let lostResponse = false;
  await page.route('**/preview-api/payroll-transactions/melissa-old/loan-deductions', async route => {
    if (route.request().method() !== 'POST' || lostResponse) return route.continue();
    lostResponse = true;
    const response = await route.fetch(); assert.equal(response.status(), 201);
    await route.abort('failed');
  });
  await deduction.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await deduction.getByRole('alert').filter({ hasText: 'Puedes reintentar' }).waitFor();
  await deduction.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await deduction.getByText('Descuento guardado.').waitFor();
  const saved = await (await page.request.get('http://127.0.0.1:3849/preview-api/payroll-transactions/melissa-old/loan-deductions')).json();
  assert.equal(saved.deductions.length, 1); assert.equal(saved.outstanding, 450000);
  await page.screenshot({ path: 'output/payroll-loan-saved.png', animations: 'disabled' });
  const paid = await page.request.post('http://127.0.0.1:3849/preview-api/payroll-transactions/melissa-old/pay', { data: { amount: 450000, paidAt: '2026-10-31', accountId: 'demo-account', reference: 'Transferencia posterior de muestra' } });
  assert.equal(paid.status(), 201);
  await deduction.getByRole('button', { name: 'Cerrar', exact: true }).first().click();
  await page.getByRole('button', { name: 'Descuentos de Melissa · ejemplo local', exact: true }).click();
  await deduction.getByRole('button', { name: 'Revertir descuento' }).click();
  await deduction.getByLabel('Motivo').fill('La cuota no correspondía a esta liquidación.');
  await deduction.getByRole('button', { name: 'Revisar', exact: true }).click();
  await page.screenshot({ path: 'output/payroll-loan-reversal-review.png', animations: 'disabled' });
  await deduction.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await deduction.getByText('Descuento revertido.').waitFor();
  const undone = await (await page.request.get('http://127.0.0.1:3849/preview-api/payroll-transactions/melissa-old/loan-deductions')).json();
  assert.equal(undone.outstanding, 300000); assert.equal(undone.paidAmount, 450000);
  assert.equal(undone.options.find(loan => loan.id === 'melissa-loan').outstanding, 900000);
  await page.screenshot({ path: 'output/payroll-loan-reversed.png', animations: 'disabled' });
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await page.screenshot({ path: 'output/payroll-periods-dark.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await deduction.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await page.screenshot({ path: 'output/payroll-periods-mobile.png', animations: 'disabled' });
  assert.deepEqual(errors, []);
  console.log('Períodos, descuento y reversión en la interfaz real: OK.');
} finally { await browser.close(); }
