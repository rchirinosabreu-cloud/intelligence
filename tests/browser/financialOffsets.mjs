import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { chooseOption } from './selectHelpers.mjs';

const base = process.env.FINANCIAL_OFFSETS_URL || 'http://127.0.0.1:3848/tests/fixtures/financial-offsets.html?year=2026&month=9';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(15000);
  await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.locator('[data-financial-kpis]').getByText(/960\.000/).waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'output/financial-offset-indicators.png', animations: 'disabled' });
  await page.getByRole('tab', { name: 'Cuentas por cobrar', exact: true }).click();
  await page.getByRole('button', { name: /Cliente de muestra · cruce/ }).click();
  await page.getByRole('button', { name: 'Saldar de otra forma', exact: true }).click();
  await chooseOption(page.getByRole('combobox', { name: 'Forma de saldar' }), 'COMPENSACION');
  const dialog = page.locator('[data-financial-offset]');
  await chooseOption(dialog.getByRole('combobox', { name: 'Cuenta por pagar del mismo tercero' }), 'offset-ap');
  await dialog.getByLabel('Fecha del cruce').fill('18/09/2026'); await dialog.getByLabel('Fecha del cruce').press('Tab');
  await dialog.getByLabel('Autorizado por').fill('Dirección · muestra local');
  await dialog.getByLabel('Motivo del cruce', { exact: true }).fill('Acuerdo de compensación entre las dos obligaciones.');
  await dialog.getByRole('button', { name: 'Revisar cruce', exact: true }).click();
  assert.match(await dialog.innerText(), /40\.000/);
  await page.screenshot({ path: 'output/financial-offset-review.png', animations: 'disabled' });
  // Simulate a lost response AFTER commit; the same request must be safe to retry.
  let lost = false;
  await page.route('**/preview-api/receivables/offset-ar/settlements', async route => {
    if (lost) return route.continue(); lost = true;
    const response = await route.fetch(); assert.equal(response.status(), 201);
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Respuesta perdida de prueba. Reintenta sin duplicar.' }) });
  });
  await dialog.getByRole('button', { name: 'Confirmar cruce', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  await dialog.getByRole('button', { name: 'Confirmar cruce', exact: true }).click();
  await dialog.getByRole('heading', { name: 'Detalle del cruce', exact: true }).waitFor();
  await dialog.getByText('Compensación vigente', { exact: false }).waitFor();
  assert.match(await dialog.innerText(), /40\.000/);
  await dialog.locator('[data-offset-history] summary').click();
  await page.screenshot({ path: 'output/financial-offset-saved.png', animations: 'disabled' });
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).first().click();
  await page.getByRole('tab', { name: 'Cuentas por pagar', exact: true }).click();
  await page.locator('[data-payable-group]').getByRole('button', { name: /Cliente de muestra/ }).click();
  await page.locator('[data-payable-payments-toggle]').click();
  await page.getByText('Compensación · sin dinero', { exact: true }).waitFor();
  assert.equal(await page.locator('[data-payable-correct]').count(), 0);
  await page.screenshot({ path: 'output/financial-offset-payables.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Ver cruce', exact: true }).click();
  await dialog.getByLabel('Motivo de reversión').fill('El acuerdo se dejó sin efecto. Se conservan las obligaciones.');
  await dialog.getByRole('button', { name: 'Revisar reversión' }).click();
  assert.match(await dialog.innerText(), /960\.000/); assert.match(await dialog.innerText(), /1\.000\.000/);
  await page.screenshot({ path: 'output/financial-offset-reversal-review.png', animations: 'disabled' });
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await page.screenshot({ path: 'output/financial-offset-dark.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await page.screenshot({ path: 'output/financial-offset-mobile.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.evaluate(() => document.documentElement.classList.remove('dark'));
  await dialog.getByRole('button', { name: 'Confirmar reversión' }).click();
  await dialog.getByRole('heading', { name: 'Cruce revertido', exact: true }).waitFor();
  await dialog.locator('[data-offset-history] summary').click();
  assert.match(await dialog.innerText(), /Historial del cruce \(2\)/);
  await page.screenshot({ path: 'output/financial-offset-reversed.png', animations: 'disabled' });
  const ledger = await (await page.request.get(new URL('/preview-api/payables-ledger?year=2026&month=9', base).href)).json();
  assert.equal(ledger.totals.outstanding, 1000000); assert.equal(ledger.totals.paidInPeriod, 0); assert.equal(ledger.totals.compensatedInPeriod, 0);
  const records = await (await page.request.get(new URL('/preview-api/records', base).href)).json();
  assert.equal(records.total, 0);
  assert.deepEqual(errors, []);
  console.log('Cruce, reintento, dos pantallas, reversión, historial y diseños claro/oscuro/móvil: OK.');
} finally { await browser.close(); }
