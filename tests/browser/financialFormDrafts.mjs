// Borradores financieros: la muestra usa únicamente respuestas en memoria, nunca la base de datos.
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { chooseOption } from './selectHelpers.mjs';
import { formDraftKey } from '../../src/lib/formDraft.js';

const base = process.env.FINANCIAL_DEMO_URL || 'http://127.0.0.1:3713/tests/fixtures/financial-integrity.html';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    page.setDefaultTimeout(10000);
    page.setDefaultNavigationTimeout(90000); // Recargar también puede compilar dependencias de la muestra local.
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 90000 });
    await page.getByRole('navigation', { name: 'Paginación de movimientos' }).waitFor();
    await page.getByRole('tab', { name: 'Cuentas por cobrar' }).click();

    await page.getByRole('button', { name: 'Registrar préstamo', exact: true }).click();
    let dialog = page.getByRole('dialog');
    await dialog.getByLabel('Nombre', { exact: true }).fill('Persona del borrador');
    await dialog.getByLabel('Valor prestado').fill('50000');
    await chooseOption(dialog.getByLabel('Cuenta de la que salió'), 'demo-account');
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await page.getByRole('button', { name: 'Registrar préstamo', exact: true }).click();
    assert.equal(await page.getByRole('dialog').getByLabel('Nombre', { exact: true }).inputValue(), 'Persona del borrador', 'cerrar el préstamo conserva su borrador');
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByRole('tab', { name: 'Cuentas por cobrar' }).click();
    await page.getByRole('button', { name: 'Registrar préstamo', exact: true }).click();
    dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel('Nombre', { exact: true }).inputValue(), 'Persona del borrador', 'recargar conserva el préstamo');
    assert.equal(await page.evaluate(() => window.__loanBody), undefined, 'recuperar el borrador no registra una operación');
    await page.evaluate(() => { const url = new URL(location.href); url.searchParams.set('loanError', '1'); history.replaceState(null, '', url); });
    await dialog.getByRole('button', { name: 'Registrar préstamo', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: 'Préstamo no guardado (simulado)' }).waitFor();
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await page.getByRole('button', { name: 'Registrar préstamo', exact: true }).click();
    dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel('Nombre', { exact: true }).inputValue(), 'Persona del borrador', 'el rechazo del servidor conserva el borrador');
    await page.evaluate(() => { const url = new URL(location.href); url.searchParams.delete('loanError'); history.replaceState(null, '', url); });
    await dialog.getByRole('button', { name: 'Registrar préstamo', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    await page.getByRole('button', { name: 'Registrar préstamo', exact: true }).click();
    dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel('Nombre', { exact: true }).inputValue(), '', 'el servidor confirmó: no vuelve a ofrecer el préstamo ya registrado');
    await dialog.getByLabel('Nombre', { exact: true }).fill('Borrador descartable');
    await dialog.getByRole('button', { name: 'Descartar borrador', exact: true }).click();
    assert.equal(await dialog.getByLabel('Nombre', { exact: true }).inputValue(), '', 'descartar limpia lo escrito sin ejecutar el préstamo');
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();

    await page.getByRole('button', { name: /Cliente de muestra/ }).click();
    const settle = page.getByRole('button', { name: 'Saldar de otra forma', exact: true }).first();
    await settle.click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel(/^Motivo/).fill('Acuerdo de prueba sin confirmar');
    await dialog.getByLabel('Autorizado por').fill('Responsable de prueba');
    await dialog.getByLabel('Valor que se da por saldado').fill('1000');
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await settle.click();
    dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel(/^Motivo/).inputValue(), 'Acuerdo de prueba sin confirmar', 'el ajuste conserva la explicación');
    await dialog.getByRole('button', { name: 'Saldar la deuda', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    await settle.click();
    dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel(/^Motivo/).inputValue(), '', 'el ajuste confirmado limpia su borrador');
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();

    await page.getByRole('tab', { name: 'Cuentas por pagar' }).click();
    await page.locator('[data-payable-new]').click();
    let payable = page.locator('[data-payable-dialog]');
    await payable.getByLabel('Concepto', { exact: true }).fill('Materiales del borrador');
    await payable.getByLabel('Valor', { exact: true }).fill('320000');
    await page.locator('[data-payable-new-third-party]').click();
    let thirdParty = page.locator('[data-third-party-dialog]');
    await thirdParty.getByLabel('Nombre', { exact: true }).fill('Proveedor del borrador');
    await thirdParty.getByLabel('Banco', { exact: true }).fill('Banco de prueba');
    await thirdParty.getByRole('button', { name: 'Cancelar', exact: true }).click();
    assert.equal(await page.getByRole('dialog').count(), 0, 'cancelar el tercero sigue cerrando todo');
    await page.locator('[data-payable-new]').click();
    payable = page.locator('[data-payable-dialog]');
    assert.equal(await payable.getByLabel('Concepto', { exact: true }).inputValue(), 'Materiales del borrador', 'ir a crear tercero no descarta la cuenta');
    await page.locator('[data-payable-new-third-party]').click();
    thirdParty = page.locator('[data-third-party-dialog]');
    assert.equal(await thirdParty.getByLabel('Nombre', { exact: true }).inputValue(), 'Proveedor del borrador', 'el tercero conserva sus datos sin guardarlos en el servidor');
    await thirdParty.getByRole('button', { name: 'Guardar tercero', exact: true }).click();
    payable = page.locator('[data-payable-dialog]');
    await payable.waitFor();
    assert.equal(await payable.getByLabel('Concepto', { exact: true }).inputValue(), 'Materiales del borrador', 'volver del tercero conserva concepto');
    assert.match(await payable.getByRole('combobox', { name: 'Tercero' }).innerText(), /Proveedor del borrador/, 'el tercero recién creado queda elegido');
    await payable.getByRole('button', { name: 'Registrar cuenta', exact: true }).click();
    await payable.waitFor({ state: 'detached' });
    await page.locator('[data-payable-new]').click();
    payable = page.locator('[data-payable-dialog]');
    assert.equal(await payable.getByLabel('Concepto', { exact: true }).inputValue(), '', 'guardar la cuenta elimina solo su borrador');
    await page.locator('[data-payable-new-third-party]').click();
    thirdParty = page.locator('[data-third-party-dialog]');
    assert.equal(await thirdParty.getByLabel('Nombre', { exact: true }).inputValue(), '', 'el tercero confirmado ya no reaparece como nuevo');
    await thirdParty.getByRole('button', { name: 'Cancelar', exact: true }).click();

    // Una actualización remota no borra el motivo escrito ni se aplica al saldo nuevo sin revisión.
    await page.goto(base, { waitUntil: 'domcontentloaded' });
    await page.getByRole('tab', { name: 'Cuentas por cobrar' }).click();
    await page.getByRole('button', { name: /Cliente de muestra/ }).click();
    await settle.click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel(/^Motivo/).fill('Explicación que debe sobrevivir al cambio remoto');
    await dialog.getByLabel('Valor que se da por saldado').fill('3456');
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    const key = formDraftKey('demo-admin', 'financial:settlement:demo-debt');
    const originalDraft = await page.evaluate(key => localStorage.getItem(key), key);
    const changed = new URL(base); changed.searchParams.set('draftRemoteChange', '1');
    await page.goto(changed.href, { waitUntil: 'domcontentloaded' });
    await page.getByRole('tab', { name: 'Cuentas por cobrar' }).click();
    await page.getByRole('button', { name: /Cliente de muestra/ }).click();
    await settle.click();
    dialog = page.getByRole('dialog');
    assert.equal(await page.evaluate(key => localStorage.getItem(key), key), originalDraft, 'el cambio remoto conserva el borrador original intacto');
    assert.equal(await dialog.getByLabel(/^Motivo/).isEnabled(), false, 'el formulario espera que la persona resuelva el conflicto');
    assert.equal(await dialog.getByRole('combobox', { name: 'Forma de saldar' }).isEnabled(), false);
    assert.equal(await dialog.getByLabel('Fecha del cierre').isEnabled(), false);
    assert.equal(await dialog.locator('fieldset').evaluate(fieldset => fieldset.inert), true, 'los controles compuestos quedan inertes');
    assert.equal(await dialog.getByRole('button', { name: 'Saldar la deuda', exact: true }).isEnabled(), false);
    assert.equal(await dialog.getByRole('button', { name: 'Cancelar', exact: true }).isEnabled(), true, 'se puede salir sin perder el borrador');
    await dialog.locator('form').evaluate(form => form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })));
    assert.equal(await page.evaluate(() => window.__receivableSettlementBody), undefined, 'ni un envío programático ejecuta el ajuste durante el conflicto');
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await settle.click();
    dialog = page.getByRole('dialog');
    await dialog.getByRole('button', { name: 'Recuperar borrador', exact: true }).click();
    assert.equal(await dialog.getByLabel(/^Motivo/).inputValue(), 'Explicación que debe sobrevivir al cambio remoto');
    assert.equal(await dialog.getByLabel('Valor que se da por saldado').inputValue(), '3.456');
    assert.match(await dialog.innerText(), /750\.000/, 'la deuda que se revisa conserva el saldo actual');
    await dialog.getByRole('button', { name: 'Descartar borrador', exact: true }).click();
    assert.equal(await dialog.getByLabel(/^Motivo/).inputValue(), '');
    assert.equal(await dialog.getByLabel('Valor que se da por saldado').inputValue(), '750.000', 'descartar recupera la versión actual, no el saldo anterior');
    assert.deepEqual(errors, []);
    console.log('Préstamo, ajuste, cuenta por pagar y tercero: cierre/recarga, error/éxito y conflicto remoto verificados sin base de datos.');
} finally {
    await browser.close();
}
