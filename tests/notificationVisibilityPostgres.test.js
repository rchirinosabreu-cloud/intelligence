import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import pg from 'pg';
import { PrismaClient } from '@prisma/client';
import { briaTestDatabaseUrl } from './support/briaTestDatabase.js';
import { getNotifications, markAsRead, markAllNotificationsAsRead } from '../src/services/notificationService.js';

const testUrl = briaTestDatabaseUrl();
test('campana: permisos vigentes filtran páginas, conteos y lecturas sin borrar el historial', { skip: !testUrl, timeout: 90000 }, async t => {
  const schema = `notice_visibility_${randomUUID().replaceAll('-', '')}`;
  const connection = new pg.Client({ connectionString: testUrl });
  await connection.connect();
  await connection.query(`CREATE SCHEMA "${schema}"`);
  await connection.query(`SET search_path TO "${schema}"`);
  const scoped = new URL(testUrl); scoped.searchParams.set('schema', schema);
  const db = new PrismaClient({ datasources: { db: { url: scoped.href } } });
  t.after(async () => { await db.$disconnect(); await connection.query(`DROP SCHEMA "${schema}" CASCADE`); await connection.end(); });
  const ddl = execFileSync(process.execPath, ['node_modules/prisma/build/index.js', 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/schema.prisma', '--script'], { encoding: 'utf8', env: { ...process.env, DATABASE_URL: scoped.href }, stdio: ['ignore', 'pipe', 'pipe'] });
  const tables = new Set(['User', 'TeamMember', 'Notification', 'OperationalTraceEvent']);
  for (const [s] of ddl.matchAll(/CREATE TYPE "[^"]+" AS ENUM \([\s\S]*?\);/g)) await connection.query(s);
  for (const [s, name] of ddl.matchAll(/CREATE TABLE "([^"]+)" \([\s\S]*?\n\);/g)) if (tables.has(name)) await connection.query(s);
  for (const [s, name] of ddl.matchAll(/CREATE (?:UNIQUE )?INDEX "[^"]+" ON "([^"]+)"[^;]+;/g)) if (tables.has(name)) await connection.query(s);
  for (const [s, name, target] of ddl.matchAll(/ALTER TABLE "([^"]+)" ADD CONSTRAINT [^;]+?REFERENCES "([^"]+)"[^;]+;/g)) if (tables.has(name) && tables.has(target)) await connection.query(s);
  const user = await db.user.create({ data: { name: 'PM ficticia', email: `${randomUUID()}@example.invalid`, password: 'fixture', role: 'PROJECT_MANAGER', modulePermissions: { financiero: false, clientes: true } } });
  await db.teamMember.create({ data: { name: user.name, role: 'Project Manager', areas: ['ADMINISTRATIVA','DIRECCION'], userId: user.id } });
  const create = (id, type, url, index) => db.notification.create({ data: { id, userId: user.id, type, url, message: id, createdAt: new Date(Date.UTC(2026,10,6,12,index)) } });
  const hidden = ['debt','formal','billing','legacy','future-debt','financial-risk'];
  await create('debt','CARTERA_VENCIDA',null,20);
  await create('formal','FORMALIZACION_PENDIENTE',null,19);
  await create('billing','FACTURACION_MENSUAL',null,18);
  await create('legacy',null,'/financiero?tab=cartera',17);
  await create('future-debt','CARTERA_NUEVA',null,16);
  await create('financial-risk','CARTERA_RIESGO','/financiero/cliente',15);
  await create('operation','CARTERA_RIESGO','/clientes/operacion/faro',14);
  await create('suspension','CLIENTE_SUSPENDIDO','/clientes/operacion/faro',13);
  await create('renewal','RENOVACION_CONTRATO','/clientes/operacion/faro',12);
  await create('enabled','PROYECTO_HABILITADO','/clientes/operacion/faro',11);
  await create('task','TEAM_TASK_COMPLETED',null,10);
  await create('general',null,null,9);
  const original = await db.notification.findMany({ where: { id: { in: hidden } }, orderBy: { id: 'asc' } });
  const other = await db.user.create({ data: { name:'Otra persona', email:`${randomUUID()}@example.invalid`, password:'fixture',role:'PROJECT_MANAGER' } });
  await db.notification.create({data:{id:'foreign',userId:other.id,message:'Privado',type:'TEAM_TASK_COMPLETED'}});
  const first = await getNotifications(user.id, { db, limit: 2 });
  assert.deepEqual(first.items.map(n=>n.id), ['operation','suspension']);
  assert.equal(first.unreadCount, 6);
  const second = await getNotifications(user.id, { db, limit: 2, cursor: first.nextCursor, unreadOnly: true });
  assert.deepEqual(second.items.map(n=>n.id), ['renewal','enabled']);
  const last = await getNotifications(user.id, { db, limit: 2, cursor: second.nextCursor });
  assert.deepEqual(last.items.map(n=>n.id), ['task','general']);
  assert.equal(last.nextCursor, null);
  assert.equal(await markAsRead('debt', user.id, { db }), false);
  assert.equal(await markAsRead('foreign', user.id, { db }), false);
  assert.equal(await markAsRead('operation', user.id, { db }), true);
  await markAllNotificationsAsRead(user.id, { db });
  assert.equal((await getNotifications(user.id, { db })).unreadCount, 0);
  assert.deepEqual(await db.notification.findMany({ where: { id: { in: hidden } }, orderBy: { id: 'asc' } }), original);
  assert.deepEqual((await db.user.findUnique({where:{id:user.id}})).modulePermissions, { financiero:false, clientes:true });
  await db.user.update({where:{id:user.id},data:{modulePermissions:{financiero:true,clientes:true}}});
  assert.equal((await getNotifications(user.id, { db })).unreadCount, 6);
  assert.equal((await getNotifications(user.id, { db })).items.length, 12);
  await db.user.update({where:{id:user.id},data:{modulePermissions:{financiero:false,clientes:true}}});
  assert.equal((await getNotifications(user.id, { db })).items.length, 6);
});
