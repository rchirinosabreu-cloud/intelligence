import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { financialCorrectionDatabase } from './support/financialCorrectionDatabase.js';
import { briaTestDatabaseUrl } from './support/briaTestDatabase.js';
import { createPayrollContract, updatePayrollContract } from '../src/services/financialPayrollContractService.js';
import { generatePayrollPeriod, payPayrollTransaction } from '../src/services/financialPayrollService.js';
import * as periods from '../src/services/payrollPeriodService.js';

test('contrato, generación mensual, actualización explícita del borrador y conservación de historia en PostgreSQL', { skip: !briaTestDatabaseUrl(), timeout: 120000 }, async t => {
  const fixture = await financialCorrectionDatabase({ additionalTables: ['PayrollPosition', 'PayrollAdjustment'] });
  t.after(fixture.close);
  const { db, actor, first } = fixture;
  const c = await createPayrollContract(db, { name: 'Persona mensual', startDate: '2026-03-01', endDate: '2026-12-31', baseSalary: 1000000 }, actor);
  const september = (await generatePayrollPeriod(db, { year: 2026, month: 9 }, actor)).transactions[0];
  // Reproduce an older monthly row: dates absent, but original generation and contract audited.
  await db.payrollTransaction.update({ where: { id: september.id }, data: { serviceStart: null, serviceEnd: null, status: 'APPROVED' } });
  await payPayrollTransaction(db, september.id, { amount: 1000000, accountId: first.id, paidAt: '2026-10-01' }, actor);
  const before = await db.payrollTransaction.findUnique({ where: { id: september.id }, include: { payments: true } });
  const november = await generatePayrollPeriod(db, { year: 2026, month: 11 }, actor);
  assert.equal(november.createdCount, 1, 'history from September does not block November');
  const draft = november.transactions[0];
  await updatePayrollContract(db, c.id, { startDate: '2026-11-01', endDate: '2026-12-31', baseSalary: 1500000 }, actor);
  assert.equal(Number((await db.payrollTransaction.findUnique({ where: { id: draft.id } })).netAmount), 1000000, 'saving contract alone never rewrites amounts');
  assert.equal(typeof periods.syncPayrollPeriod, 'function');
  const review = await periods.readPayrollPeriods(db, c.id, actor);
  const input = { requestId: randomUUID(), expectedRevision: review.revision, reason: 'Aplicar nuevo valor al borrador de noviembre', reviewContractId: c.id };
  const synced = await periods.syncPayrollPeriod(db, draft.id, input, actor);
  assert.equal(Number(synced.transaction.netAmount), 1500000);
  assert.equal((await periods.syncPayrollPeriod(db, draft.id, input, actor)).replayed, true);
  await assert.rejects(periods.syncPayrollPeriod(db, september.id, { ...input, requestId: randomUUID(), expectedRevision: (await periods.readPayrollPeriods(db, c.id, actor)).revision }, actor), { code: 'PAYROLL_DRAFT_REQUIRED' });
  assert.deepEqual(await db.payrollTransaction.findUnique({ where: { id: september.id }, include: { payments: true } }), before);
  const latest = await periods.readPayrollPeriods(db, c.id, actor);
  await updatePayrollContract(db, c.id, { baseSalary: 1600000 }, actor);
  await assert.rejects(periods.syncPayrollPeriod(db, draft.id, { ...input, requestId: randomUUID(), expectedRevision: latest.revision }, actor), { code: 'PAYROLL_REVIEW_CHANGED' });
  assert.equal((await db.financialAuditEvent.findMany({ where: { entityId: draft.id } })).filter(e => e.after?.operation === 'PERIOD_CONTRACT_SYNC').length, 1);
  const fresh = async () => ({ ...input, requestId: randomUUID(), expectedRevision: (await periods.readPayrollPeriods(db, c.id, actor)).revision });
  const approvedInput = await fresh();
  const closed = await db.financialPeriod.create({ data: { year: 2026, month: 11, status: 'CLOSED' } });
  await assert.rejects(periods.syncPayrollPeriod(db, draft.id, approvedInput, actor), { statusCode: 409 });
  await db.financialPeriod.delete({ where: { id: closed.id } });
  await db.user.update({ where: { id: actor.id }, data: { isActive: false } });
  await assert.rejects(periods.syncPayrollPeriod(db, draft.id, approvedInput, actor), { statusCode: 403 });
  await db.user.update({ where: { id: actor.id }, data: { isActive: true } });
  const unchanged = await db.payrollTransaction.findUnique({ where: { id: draft.id } });
  const broken = { $transaction: work => db.$transaction(tx => work({ ...tx, financialAuditEvent: { ...tx.financialAuditEvent, create: async () => { throw new Error('falló historial'); } } })) };
  await assert.rejects(periods.syncPayrollPeriod(broken, draft.id, await fresh(), actor), /falló historial/);
  assert.deepEqual(await db.payrollTransaction.findUnique({ where: { id: draft.id } }), unchanged);
  const concurrentInput = await fresh();
  const concurrent = await Promise.allSettled([concurrentInput, { ...concurrentInput, requestId: randomUUID() }].map(body => periods.syncPayrollPeriod(db, draft.id, body, actor)));
  assert.equal(concurrent.filter(r => r.status === 'fulfilled').length, 1);
  assert.deepEqual(await db.payrollTransaction.findUnique({ where: { id: september.id }, include: { payments: true } }), before);
});

test('Jesu: pago de octubre en noviembre, generación concurrente y fila mensual revertida conservados', { skip: !briaTestDatabaseUrl(), timeout: 120000 }, async t => {
  const fixture = await financialCorrectionDatabase({ additionalTables: ['PayrollPosition', 'PayrollAdjustment'] }); t.after(fixture.close);
  const { db, actor, first } = fixture;
  const c = await createPayrollContract(db, { name: 'Jesu de prueba', startDate: '2026-10-16', endDate: '2026-10-31', baseSalary: 750000 }, actor);
  const october = await db.payrollTransaction.create({ data: { contractId: c.id, year: 2026, month: 11, periodKey: 'october', serviceStart: new Date('2026-10-16'), serviceEnd: new Date('2026-10-31'), status: 'APPROVED', baseSalary: 750000, grossAmount: 750000, netAmount: 750000 } });
  const payment = await payPayrollTransaction(db, october.id, { amount: 750000, accountId: first.id, paidAt: '2026-11-09' }, actor);
  await updatePayrollContract(db, c.id, { startDate: '2026-11-01', endDate: '2026-12-31', baseSalary: 1500000 }, actor);
  const obsolete = await db.payrollTransaction.create({ data: { contractId: c.id, year: 2026, month: 11, baseSalary: 1, grossAmount: 1, netAmount: 1, voidedAt: new Date(), voidReason: 'Anterior sin vigencia' } });
  const results = await Promise.allSettled([1,2].map(() => generatePayrollPeriod(db, { year: 2026, month: 11 }, actor)));
  assert.ok(results.some(r => r.status === 'fulfilled'));
  const rows = await db.payrollTransaction.findMany({ where: { contractId: c.id, voidedAt: null } });
  assert.equal(rows.length, 2);
  assert.equal(Number(rows.find(r => r.id !== october.id).netAmount), 1500000);
  assert.equal((await generatePayrollPeriod(db, { year: 2026, month: 11 }, actor)).createdCount, 0);
  assert.deepEqual(await db.payrollPayment.findUnique({ where: { id: payment.payment.id } }), payment.payment);
  assert.deepEqual(await db.payrollTransaction.findUnique({ where: { id: obsolete.id } }), obsolete);
});
